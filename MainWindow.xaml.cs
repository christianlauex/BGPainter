using System;
using System.IO;
using System.Runtime.InteropServices;
using System.Threading.Tasks;
using System.Windows;
using System.Windows.Media;
using System.Windows.Media.Imaging;
using Microsoft.Win32;
using Windows.Storage;
using Windows.System.UserProfile;

namespace Backgroundcolourist
{
    public partial class MainWindow : Window
    {
        [DllImport("user32.dll", CharSet = CharSet.Auto)]
        private static extern int SystemParametersInfo(int uAction, int uParam, string lpvParam, int fuWinIni);

        private const int SPI_SETDESKWALLPAPER = 0x0014;
        private const int SPIF_UPDATEINIFILE = 0x01;
        private const int SPIF_SENDCHANGE = 0x02;

        // Dedicated app folder inside system temp path
        // C:\Users\Username\AppData\Local\Temp\Backgroundcolourist
        private readonly string _tempFolder = Path.Combine(Path.GetTempPath(), "Backgroundcolourist");
        
        private string? _tempColorImagePath;
        private string? _tempBwImagePath;

        public MainWindow()
        {
            InitializeComponent();
            
            // Ensure the temporary directory exists on app startup
            Directory.CreateDirectory(_tempFolder);
        }

        private void SelectBtn_Click(object sender, RoutedEventArgs e)
        {
            OpenFileDialog openFileDialog = new OpenFileDialog
            {
                Filter = "Image Files (*.png;*.jpg;*.jpeg)|*.png;*.jpg;*.jpeg"
            };

            if (openFileDialog.ShowDialog() == true)
            {
                try
                {
                    string originalPath = openFileDialog.FileName;

                    // Step 1: Clear previously generated temporary files
                    ClearTempFolder();

                    // Define output file paths in temp directory
                    string extension = Path.GetExtension(originalPath);
                    _tempColorImagePath = Path.Combine(_tempFolder, $"desktop_color{extension}");
                    _tempBwImagePath = Path.Combine(_tempFolder, "lockscreen_bw.png");

                    // Step 2: Copy uploaded image to temp directory for home screen
                    File.Copy(originalPath, _tempColorImagePath, overwrite: true);

                    // Step 3: Convert to B&W and save to temp directory for lock screen
                    FormatConvertedBitmap bwBitmap = CreateGrayscaleBitmap(_tempColorImagePath);
                    SaveBitmapToFile(bwBitmap, _tempBwImagePath);

                    // Step 4: Load previews into UI using memory cache (avoids locking temp files)
                    DesktopPreviewImage.Source = LoadBitmapFromPath(_tempColorImagePath);
                    DesktopPlaceholder.Visibility = Visibility.Collapsed;

                    LockScreenPreviewImage.Source = LoadBitmapFromPath(_tempBwImagePath);
                    LockScreenPlaceholder.Visibility = Visibility.Collapsed;

                    ApplyBtn.IsEnabled = true;
                    StatusText.Text = "Previews generated in temp folder. Click 'Apply Wallpapers' to set them.";
                }
                catch (Exception ex)
                {
                    MessageBox.Show($"Error processing image: {ex.Message}", "Error", MessageBoxButton.OK, MessageBoxImage.Error);
                }
            }
        }

        private async void ApplyBtn_Click(object sender, RoutedEventArgs e)
        {
            if (string.IsNullOrEmpty(_tempColorImagePath) || string.IsNullOrEmpty(_tempBwImagePath))
            {
                return;
            }

            try
            {
                StatusText.Text = "Applying wallpapers...";

                // Apply color copy from temp folder as Desktop Wallpaper
                SetDesktopWallpaper(_tempColorImagePath);

                // Apply B&W image from temp folder as Lock Screen
                bool lockScreenSuccess = await SetLockScreenAsync(_tempBwImagePath);

                if (lockScreenSuccess)
                {
                    StatusText.Text = "Successfully applied Desktop and Lock Screen from temp storage!";
                }
                else
                {
                    StatusText.Text = "Desktop updated. Lock screen update failed or unsupported.";
                }
            }
            catch (Exception ex)
            {
                MessageBox.Show($"Error applying images: {ex.Message}", "Error", MessageBoxButton.OK, MessageBoxImage.Error);
                StatusText.Text = "Operation failed.";
            }
        }

        // Deletes all temporary images generated by previous uploads
        private void ClearTempFolder()
        {
            // Clear UI preview bindings first
            DesktopPreviewImage.Source = null;
            LockScreenPreviewImage.Source = null;

            if (Directory.Exists(_tempFolder))
            {
                DirectoryInfo di = new DirectoryInfo(_tempFolder);
                foreach (FileInfo file in di.GetFiles())
                {
                    try
                    {
                        file.Delete();
                    }
                    catch
                    {
                        // Ignore files if locked by an external process
                    }
                }
            }
        }

        // Helper: Loads image into memory without leaving open file handle locks
        private BitmapImage LoadBitmapFromPath(string filePath)
        {
            // Read the file bytes directly into memory to completely avoid disk file-locking
            byte[] imageBytes = File.ReadAllBytes(filePath);

            using (MemoryStream ms = new MemoryStream(imageBytes))
            {
                BitmapImage bitmap = new BitmapImage();
                bitmap.BeginInit();
                bitmap.CacheOption = BitmapCacheOption.OnLoad; // Loads image completely into RAM
                bitmap.StreamSource = ms;
                bitmap.EndInit();
                bitmap.Freeze(); // Freezes memory handle so it can be passed across threads freely
                return bitmap;
            }
        }

        private FormatConvertedBitmap CreateGrayscaleBitmap(string sourcePath)
        {
            // Load safely from memory
            BitmapImage bitmap = LoadBitmapFromPath(sourcePath);

            FormatConvertedBitmap bwBitmap = new FormatConvertedBitmap();
            bwBitmap.BeginInit();
            bwBitmap.Source = bitmap;
            // FormatConvertedBitmap handles RGB-to-Gray8 seamlessly once loaded in RAM
            bwBitmap.DestinationFormat = PixelFormats.Gray8; 
            bwBitmap.EndInit();
            bwBitmap.Freeze();

            return bwBitmap;
        }

        private void SaveBitmapToFile(BitmapSource bitmapSource, string destinationPath)
        {
            PngBitmapEncoder encoder = new PngBitmapEncoder();
            encoder.Frames.Add(BitmapFrame.Create(bitmapSource));

            using FileStream stream = new FileStream(destinationPath, FileMode.Create);
            encoder.Save(stream);
        }

        private void SetDesktopWallpaper(string imagePath)
        {
            SystemParametersInfo(SPI_SETDESKWALLPAPER, 0, imagePath, SPIF_UPDATEINIFILE | SPIF_SENDCHANGE);
        }

        public async Task<bool> SetLockScreenAsync(string imagePath)
        {
            try
            {
                // WinRT APIs require a WinRT StorageFile object instead of a standard .NET file path
                StorageFile file = await StorageFile.GetFileFromPathAsync(imagePath);

                // Update the lock screen image

                // UserProfilePersonalizationSettings profileSettings = UserProfilePersonalizationSettings.Current;
                // return await profileSettings.TrySetLockScreenImageAsync(file);

                await LockScreen.SetImageFileAsync(file);
                
                return true;
            }
            catch (UnauthorizedAccessException)
            {
                MessageBox.Show("Access denied. The application lacks permission or group policies are blocking this change.", "Error", MessageBoxButton.OK, MessageBoxImage.Warning);
                return false;
            }
        }

        // Clean up temp folder when app closes
        protected override void OnClosed(EventArgs e)
        {
            base.OnClosed(e);
            ClearTempFolder();
        }
    }
}